#!/usr/bin/env python3
"""Build the Metal backend's anti-aliasing passes from the Vulkan backend's.

Run with glslangValidator and spirv-cross on PATH:
    python3 tools/metal_post_shaders.py
The generated C (port/macos/xgpu_metal_post_shaders.c) embeds the Metal
Shading Language of display.anti_aliasing's passes and SMAA's lookup
textures, inflated; the game needs no shader compiler of its own and no zlib
for them. --check verifies that the checked-in file still matches its
sources.

The passes are those of the Vulkan backend (tools/vulkan_post_shaders.py,
whose GLSL they are): its vertex shader, FXAA, and the main functions of
SMAA's three passes after SMAA.hlsl (port/third_party/smaa). Their GLSL is
compiled to SPIR-V as Vulkan's is, then written as MSL by SPIRV-Cross, so
the two backends run the same passes, display.ambient_occlusion's too
(with a fill of its own, the uniforms' first vector as the colour), and
display.gamma's curve, which the presentation draws (host_metal.m). Only
the interface changes: the uniforms' block is at the Metal backend's draw
uniforms (buffer XGPU_METAL_BUFFER_DRAW_UNIFORMS,
port/macos/xgpu_metal_bindings.h), each texture and its sampler at the
texture unit Vulkan's UNITS gives it, and each function is named for its pass.
The coordinates stay: Metal's textures and targets have their first row at
the top, as Vulkan's do, and [[position]] counts rows from it in both; the
vertex shader's one triangle covers the viewport whichever way up it is.
glslang 16.6.0 and SPIRV-Cross (Homebrew's, 2026-09) produce the checked-in
text.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import sys
import zlib

sys.path.insert(0, str(Path(__file__).resolve().parent))
import vulkan_post_shaders as vulkan  # noqa: E402

ROOT = vulkan.ROOT
OUTPUT = ROOT / "port/macos/xgpu_metal_post_shaders.c"
# xgpu_metal_bindings.h's XGPU_METAL_BUFFER_DRAW_UNIFORMS
UNIFORMS_BUFFER = 17
# the passes, in xgpu_metal_post_shaders.h's order, and their functions' names
PROGRAMS = (("post", "vert", "xgpu_post_vertex"), ("fxaa", "frag", "xgpu_post_fxaa"),
            ("smaa_edges", "frag", "xgpu_post_smaa_edges"), ("smaa_weights", "frag", "xgpu_post_smaa_weights"),
            ("smaa_blend", "frag", "xgpu_post_smaa_blend"), ("hdr_tone_map", "frag", "xgpu_hdr_tone_map"),
            ("hdr_encode", "frag", "xgpu_hdr_encode"), ("occlusion_depth", "frag", "xgpu_occlusion_depth"),
            ("occlusion", "frag", "xgpu_occlusion"), ("occlusion_blur", "frag", "xgpu_occlusion_blur"),
            ("occlusion_apply", "frag", "xgpu_occlusion_apply"), ("occlusion_fill", "frag", "xgpu_occlusion_fill"),
            ("gamma", "frag", "xgpu_gamma"))
# display.hdr's tone map reads the pixel it draws over (its input
# attachment) as Metal's programmable blending does: [[color(0)]]
FRAMEBUFFER_FETCH = ("hdr_tone_map",)
MSL_VERSION = "20300"
# display.ambient_occlusion's fill (its mask emptied and marked, its view
# alone's white): the uniforms' metrics as the colour, as Vulkan's clears'
# shader writes its colour
OCCLUSION_FILL_SOURCE = (
    "uniform vec4 metrics;\n"
    "out vec4 result;\n"
    "\n"
    "void main()\n"
    "{\n"
    "\tresult = metrics;\n"
    "}\n"
)


def c_string(name: str, text: str) -> str:
    """text as a C string constant, a line of the source to a line."""
    lines = [f"static const char {name}[] ="]
    for line in text.splitlines(keepends=True):
        escaped = line.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t").replace("\n", "\\n")
        lines.append(f'\t"{escaped}"')
    lines[-1] += ";\n"
    return "\n".join(lines)


def generate(args):
    build = args.build_dir
    build.mkdir(parents=True, exist_ok=True)
    hlsl = vulkan.smaa_hlsl()
    codes = {
        "post": vulkan.VERTEX_SOURCE,
        "fxaa": vulkan.FXAA_SOURCE,
    }
    for name, main in zip(("smaa_edges", "smaa_weights", "smaa_blend"), vulkan.SMAA_MAINS):
        codes[name] = vulkan.SMAA_PREFIX + hlsl + "\n" + main
    for name, code in vulkan.hdr_programs().items():
        codes[f"hdr_{name}"] = code
    codes["occlusion_depth"] = vulkan.OCCLUSION_DEPTH_SOURCE
    codes["occlusion"] = vulkan.OCCLUSION_SOURCE
    codes["occlusion_blur"] = vulkan.OCCLUSION_BLUR_SOURCE
    codes["occlusion_apply"] = vulkan.OCCLUSION_APPLY_SOURCE
    codes["occlusion_fill"] = OCCLUSION_FILL_SOURCE
    codes["gamma"] = vulkan.GAMMA_SOURCE
    text = [
        "/* Generated by tools/metal_post_shaders.py from Vulkan's GLSL, xgpu_hdr.c and port/third_party/smaa. "
        "Do not edit. */\n",
        '#include "xgpu_metal_post_shaders.h"\n',
    ]
    for name, stage, entry in PROGRAMS:
        glsl = vulkan.translate(stage, codes[name], vulkan.UNITS)
        # (the uniforms' block at the Metal backend's draw uniforms; the
        # textures need no set: one table of each kind)
        glsl = glsl.replace("set = 0, binding = 1)", f"set = 0, binding = {UNIFORMS_BUFFER})")
        path = build / f"{name}.{stage}"
        path.write_text(glsl)
        spv = path.with_suffix(f".{stage}.spv")
        spv.unlink(missing_ok=True)
        subprocess.run([args.compiler, "-V", "--target-env", "vulkan1.1", "-o", str(spv), str(path)],
                       check=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        fetch = ["--msl-framebuffer-fetch"] if name in FRAMEBUFFER_FETCH else []
        msl = subprocess.run([args.cross, str(spv), "--msl", "--msl-version", MSL_VERSION, "--msl-decoration-binding",
                              *fetch, "--rename-entry-point", "main", entry, stage],
                             check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True).stdout
        if entry not in msl:
            raise ValueError(f"{name}: SPIRV-Cross did not name its function {entry}")
        (build / f"{name}.metal").write_text(msl)
        text.append(c_string(f"{name}_source", msl))
        print(f"{name}: {len(msl)} bytes of MSL")
    text.append("const struct xgpu_metal_post_function xgpu_metal_post_functions[XGPU_METAL_POST_FUNCTION_COUNT] =\n{")
    for name, _, entry in PROGRAMS:
        text.append(f'\t{{ {name}_source, sizeof({name}_source) - 1, "{entry}" }},')
    text.append("};\n")
    for name, file, width, height, channels in vulkan.TEXTURES:
        texels = zlib.decompress((vulkan.SMAA / file).read_bytes())
        if len(texels) != width * height * channels:
            raise ValueError(f"{file} is {len(texels)} bytes, not {width}x{height}x{channels}")
        text.append(vulkan.words_array(f"xgpu_metal_post_{name}_texture", texels, public=True))
    generated = "\n".join(text)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit(f"{OUTPUT.relative_to(ROOT)} differs; regenerate it")
    else:
        OUTPUT.write_text(generated)
    if args.metal:
        # (each function compiles for the Mac, as the backend compiles it)
        for name, _, _ in PROGRAMS:
            subprocess.run(["xcrun", "-sdk", "macosx", "metal", "-std=metal3.1", "-mmacosx-version-min=14.4",
                            "-fmetal-math-mode=safe", "-c", str(build / f"{name}.metal"), "-o",
                            str(build / f"{name}.air")], check=True)
        print(f"{len(PROGRAMS)} functions compiled for Metal")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--compiler", default="glslangValidator")
    parser.add_argument("--cross", default="spirv-cross")
    parser.add_argument("--build-dir", type=Path, default=ROOT / "build/metal_post_shaders")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--metal", action="store_true", help="also compile each function with the Metal compiler")
    args = parser.parse_args()
    try:
        generate(args)
    except subprocess.CalledProcessError as error:
        if error.stdout:
            print(error.stdout if isinstance(error.stdout, str) else error.stdout.decode())
        if error.stderr:
            print(error.stderr if isinstance(error.stderr, str) else error.stderr.decode())
        raise


if __name__ == "__main__":
    main()
