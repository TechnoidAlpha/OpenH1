/*
XGPU_METAL_POST_SHADERS.H

display.anti_aliasing's passes in the Metal Shading Language, generated by
tools/metal_post_shaders.py from the Vulkan backend's GLSL
(tools/vulkan_post_shaders.py, and SMAA.hlsl of port/third_party/smaa), by
way of the SPIR-V the Vulkan backend's are, and SMAA's lookup textures. The
vertex function draws one triangle over the viewport, from the vertex's
index (no vertex data). The fragment functions' uniforms are struct
xgpu_metal_post_uniforms at buffer XGPU_METAL_BUFFER_DRAW_UNIFORMS (the
draw's uniforms). Their textures and samplers are the GLSL's texture
units: FXAA and SMAA's edges read the target's copy (0); the blending
weights the edges (0), the area texture (1) and the search texture (2); the
blend the target's copy (0) and the weights (1).
*/

#ifndef XGPU_METAL_POST_SHADERS_H
#define XGPU_METAL_POST_SHADERS_H

#include <stddef.h>
#include <stdint.h>

enum
{
	XGPU_METAL_POST_VERTEX,
	XGPU_METAL_POST_FXAA,
	XGPU_METAL_POST_SMAA_EDGES,
	XGPU_METAL_POST_SMAA_WEIGHTS,
	XGPU_METAL_POST_SMAA_BLEND,
	/* display.hdr's (port/linux/src/xgpu_hdr.c): the tone map, which reads
	the pixel it draws over ([[color(0)]]: programmable blending), and the
	encoding, which samples the frame (texture 0) over the viewport */
	XGPU_METAL_POST_HDR_TONE_MAP,
	XGPU_METAL_POST_HDR_ENCODE,
	/* display.ambient_occlusion's (Vulkan's: xgpu_vulkan_post.c), and a
	fill of the uniforms' metrics */
	XGPU_METAL_POST_OCCLUSION_DEPTH,
	XGPU_METAL_POST_OCCLUSION,
	XGPU_METAL_POST_OCCLUSION_BLUR,
	XGPU_METAL_POST_OCCLUSION_APPLY,
	XGPU_METAL_POST_OCCLUSION_FILL,
	/* display.gamma's curve (the Vulkan backend's), which the presentation
	draws into an SDR drawable, sampling the frame (texture 0) over the
	viewport */
	XGPU_METAL_POST_GAMMA,
	XGPU_METAL_POST_FUNCTION_COUNT
};

/* (std140: the Vulkan backend's struct xgpu_vulkan_post_uniforms) */
struct xgpu_metal_post_uniforms
{
	/* 1 / width, 1 / height, width, height of the target */
	float metrics[4];
	/* FXAA's: the rectangle's outermost texel centres, as texture
	coordinates (x0, y0, x1, y1); display.gamma's: the power (x), its
	metrics the viewport's x, y, 1 / width, 1 / height */
	float bounds[4];
	/* display.hdr's: the tone map's mode and peak; the encoding's paper
	white, peak and output (xgpu_hdr.h; its metrics are the viewport's x, y,
	1 / width, 1 / height) */
	float hdr[4];
	/* display.ambient_occlusion's: as the Vulkan backend's */
	float camera[4];
	float occlusion[4];
	float sampling[4];
};

/* a function's source (each its own: SPIRV-Cross names the structures
alike), its length and its name */
struct xgpu_metal_post_function
{
	const char *source;
	size_t size;
	const char *entry;
};

extern const struct xgpu_metal_post_function xgpu_metal_post_functions[XGPU_METAL_POST_FUNCTION_COUNT];

/* SMAA's lookup textures, their texels' bytes four to a word (the first in
the lowest bits): the area texture's two channels, the search texture's
one */
#define XGPU_METAL_POST_AREA_WIDTH 160
#define XGPU_METAL_POST_AREA_HEIGHT 560
#define XGPU_METAL_POST_SEARCH_WIDTH 64
#define XGPU_METAL_POST_SEARCH_HEIGHT 16
extern const uint32_t xgpu_metal_post_area_texture[];
extern const uint32_t xgpu_metal_post_search_texture[];

#endif
