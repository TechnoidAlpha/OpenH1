/*
XGPU_METAL_COMBINER.C

The NV2A's pixel stage as one Metal fragment function whose constants are a
pixel program's configuration (xgpu_metal_combiner.h). It does what the MSL
emitter's pixel shaders do (port/linux/src/xgpu_msl.c), operation for
operation, with the program's choices read from the constants instead of
written into the code; each register a choice the constants fold (selects,
not memory: a register file indexed at run time would be).
*/

#include "xgpu.h"
#include "xgpu_shader.h"
#include "xgpu_metal_combiner.h"

#include <string.h>

_Static_assert(sizeof(struct xgpu_metal_combiner) == 160, "the combiner's configuration");

int xgpu_metal_combiner_draws(const struct xgpu_pixel_program *program)
{
	return !program->per_pixel_lighting && !program->dynamic_lights && !program->alpha_test_samples &&
		!program->multiview && !program->hdr;
}

static uint32_t input_bits(const struct xgpu_combiner_input *input)
{
	return (uint32_t)(input->reg & 15) | ((uint32_t)(input->alpha != 0) << 4) | ((uint32_t)(input->mapping & 7) << 5);
}

void xgpu_metal_combiner_configure(const struct xgpu_pixel_program *program, const uint8_t border[4],
	struct xgpu_metal_combiner *combiner)
{
	const struct xgpu_final_combiner *final = &program->final;
	/* (D3DCMP_NEVER ... ALWAYS as 1 ... 8) */
	uint32_t alpha_test = program->alpha_test >= D3DCMP_NEVER && program->alpha_test <= D3DCMP_ALWAYS ?
		(uint32_t)(program->alpha_test - D3DCMP_NEVER + 1) : 0;
	int stage, portion, input;

	memset(combiner, 0, sizeof(*combiner));
	for (stage = 0; stage < 4; stage++)
	{
		const struct xgpu_texture_stage *texture = &program->stages[stage];

		combiner->stages[stage] = (uint32_t)(texture->mode & 31) | ((uint32_t)(texture->sampler & 7) << 5) |
			((uint32_t)(texture->input & 3) << 8) | ((uint32_t)((texture->previous + 1) & 3) << 10) |
			((uint32_t)(texture->dot_mapping & 7) << 12) | ((uint32_t)(texture->compare & 15) << 15) |
			((uint32_t)(texture->color_sign & 15) << 19) | ((uint32_t)(texture->alpha_kill != 0) << 23) |
			((uint32_t)(border[stage] & 7) << 24);
	}
	combiner->flags = (uint32_t)(program->combiner_count & 15) | ((uint32_t)(program->mux_msb != 0) << 4) |
		((uint32_t)(program->fog != 0) << 5) | ((uint32_t)(program->fog_mode & 7) << 6) |
		((uint32_t)(alpha_test & 15) << 9) | ((uint32_t)(program->coverage_alpha != 0) << 13) |
		((uint32_t)(program->point_threshold != 0) << 14) | ((uint32_t)(program->source_blend & 7) << 15) |
		((uint32_t)(final->present != 0) << 18) | ((uint32_t)(final->clamp_sum != 0) << 19) |
		((uint32_t)(final->invert_v1 != 0) << 20) | ((uint32_t)(final->invert_r0 != 0) << 21);
	for (input = 0; input < 7; input++)
		combiner->final_inputs[input / 4] |= input_bits(&final->inputs[input]) << (8 * (input % 4));
	for (stage = 0; stage < (int)program->combiner_count && stage < 8; stage++)
	{
		const struct xgpu_combiner_stage *general = &program->combiners[stage];

		for (portion = 0; portion < 2; portion++)
		{
			const struct xgpu_combiner_portion *part = &general->portions[portion];

			for (input = 0; input < 4; input++)
				combiner->combiners[stage].inputs[portion] |= input_bits(&part->inputs[input]) << (8 * input);
			combiner->combiners[stage].control[portion] = (uint32_t)(part->ab_dot != 0) |
				((uint32_t)(part->cd_dot != 0) << 1) | ((uint32_t)(part->mux != 0) << 2) |
				((uint32_t)(part->output_mapping & 7) << 3) | ((uint32_t)(part->ab & 15) << 6) |
				((uint32_t)(part->cd & 15) << 10) | ((uint32_t)(part->sum & 15) << 14) |
				((uint32_t)(part->ab_blue_to_alpha != 0) << 18) | ((uint32_t)(part->cd_blue_to_alpha != 0) << 19);
		}
		combiner->combiners[stage].control[1] |= ((uint32_t)(general->c0 & 7) << 24) | ((uint32_t)(general->c1 & 7) << 27);
	}
}

void xgpu_metal_combiner_constants(const struct xgpu_metal_combiner *combiner,
	uint32_t constants[XGPU_METAL_COMBINER_CONSTANTS])
{
	int index;

	for (index = 0; index < 4; index++)
		constants[index] = combiner->stages[index];
	constants[4] = combiner->flags;
	constants[5] = combiner->final_inputs[0];
	constants[6] = combiner->final_inputs[1];
	for (index = 0; index < 8; index++)
	{
		constants[7 + 4 * index] = combiner->combiners[index].inputs[0];
		constants[8 + 4 * index] = combiner->combiners[index].inputs[1];
		constants[9 + 4 * index] = combiner->combiners[index].control[0];
		constants[10 + 4 * index] = combiner->combiners[index].control[1];
	}
}

