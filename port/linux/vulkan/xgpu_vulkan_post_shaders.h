/*
XGPU_VULKAN_POST_SHADERS.H

display.anti_aliasing's passes as SPIR-V, generated by
tools/vulkan_post_shaders.py from its GLSL (and SMAA.hlsl of
port/third_party/smaa),
display.hdr's tone map and encoding (port/linux/src/xgpu_hdr.c, the GLSL
Metal's are compiled from), and SMAA's lookup textures. The vertex shader draws one triangle over the
viewport, from the vertex's index (no vertex data). The fragment programs'
uniforms are a block at set 0, binding 1: struct xgpu_vulkan_post_uniforms.
Their textures are set 1's bindings, the tool's texture units: FXAA and
SMAA's edges read the target's copy (0); the blending weights the edges (0),
the area texture (1) and the search texture (2); the blend the target's copy
(0) and the weights (1); the turn, the encoding and display.gamma's curve
the frame (0). The tone map reads the pixel it draws over as input
attachment 0 of set 2 (binding 0), each sample's own in its multisampled
variant. The ambient occlusion's
passes read the depth target, the distances, or the occlusion (0).
*/

#ifndef XGPU_VULKAN_POST_SHADERS_H
#define XGPU_VULKAN_POST_SHADERS_H

#include <stdint.h>
#include <stddef.h>

enum xgpu_vulkan_post_program_id
{
	XGPU_VULKAN_POST_FXAA,
	XGPU_VULKAN_POST_SMAA_EDGES,
	XGPU_VULKAN_POST_SMAA_WEIGHTS,
	XGPU_VULKAN_POST_SMAA_BLEND,
	/* (Vulkan's own: the frame turned for the swapchain, xgpu_vulkan_post_rotate) */
	XGPU_VULKAN_POST_ROTATE,
	/* display.hdr's (xgpu_hdr.c): the tone map in place, of a target of one
	sample and of more, and the encoding for the display */
	XGPU_VULKAN_POST_HDR_TONE_MAP,
	XGPU_VULKAN_POST_HDR_TONE_MAP_MS,
	XGPU_VULKAN_POST_HDR_ENCODE,
	/* (Vulkan's own) display.ambient_occlusion's: the depth made distances,
	the occlusion (GTAO), its blur along a direction, and its laying over
	the target (or its drawing alone) */
	XGPU_VULKAN_POST_OCCLUSION_DEPTH,
	XGPU_VULKAN_POST_OCCLUSION,
	XGPU_VULKAN_POST_OCCLUSION_BLUR,
	XGPU_VULKAN_POST_OCCLUSION_APPLY,
	/* display.gamma's curve over an SDR frame (xgpu_vulkan_post_gamma) */
	XGPU_VULKAN_POST_GAMMA,
	XGPU_VULKAN_POST_PROGRAM_COUNT
};

/* (std140) */
struct xgpu_vulkan_post_uniforms
{
	/* 1 / width, 1 / height, width, height of the target */
	float metrics[4];
	/* FXAA's: the rectangle's outermost texel centres, as texture
	coordinates (x0, y0, x1, y1); the turn's: its matrix's rows (the
	turned image's coordinates about its centre to the frame's); display.
	gamma's: the power (x), its metrics the viewport's x, y, 1 / width and
	1 / height */
	float bounds[4];
	/* display.hdr's: the tone map's mode and peak; the encoding's paper
	white, peak and output (xgpu_hdr.c), its metrics the viewport's x, y,
	1 / width and 1 / height */
	float hdr[4];
	/* display.ambient_occlusion's (tools/vulkan_post_shaders.py): the
	projection's x and y scales and offsets; the near and far planes, the
	radius and the strength; the slices, the steps, the power and the
	target's pixels to the occlusion's, or the blur's direction. Their
	bounds the 3D view in the occlusion's pixels */
	float camera[4];
	float occlusion[4];
	float sampling[4];
};

struct xgpu_vulkan_post_module
{
	const uint32_t *words;
	size_t count;
};

extern const struct xgpu_vulkan_post_module xgpu_vulkan_post_vertex;
extern const struct xgpu_vulkan_post_module xgpu_vulkan_post_programs[XGPU_VULKAN_POST_PROGRAM_COUNT];
/* the core's clears of some of a colour target's channels (xgpu_vulkan.c):
drawn with the vertex shader above, it writes the colour of its uniforms'
block (set 0, binding 1: a vec4) */
extern const struct xgpu_vulkan_post_module xgpu_vulkan_post_clear;

/* SMAA's lookup textures, their texels' bytes four to a word (the first in
the lowest bits): the area texture's two channels, the search texture's
one */
#define XGPU_VULKAN_POST_AREA_WIDTH 160
#define XGPU_VULKAN_POST_AREA_HEIGHT 560
#define XGPU_VULKAN_POST_SEARCH_WIDTH 64
#define XGPU_VULKAN_POST_SEARCH_HEIGHT 16
extern const uint32_t xgpu_vulkan_post_area_texture[];
extern const uint32_t xgpu_vulkan_post_search_texture[];

#endif
